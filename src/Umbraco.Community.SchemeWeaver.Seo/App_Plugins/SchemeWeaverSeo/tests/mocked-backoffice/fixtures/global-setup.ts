import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

/**
 * Playwright globalSetup for the SEO bundle's mocked-backoffice tier.
 *
 * The SEO bundle compiles a few core modules through `src/core-bridge/` (relative imports
 * into the core plugin's src/). Vite's `fs.allow` is scoped to the Umbraco client checkout,
 * so the harness builds a COMPOSITE mirror under `examples/schemeweaver-seo/`:
 *
 *   examples/schemeweaver-seo/
 *     core/      copy of the core plugin's src/ (its manifests + MSW handlers)
 *     seo/       copy of this plugin's src/, with core-bridge rewritten to ../../core/
 *     index.ts   aggregates both manifest lists so VITE_EXAMPLE_PATH loads them together
 *
 * Both bundles' MSW handlers register (the core's first, then the SEO ones), so the backoffice
 * can show the SEO Schema section and the page Schema tab without a .NET host.
 */

const PINNED_UMBRACO_VERSION = '17.2.2';
const MIRROR_SUBPATH = 'examples/schemeweaver-seo';

const SEO_SRC = resolve(__dirname, '..', '..', '..', 'src');
const CORE_SRC = resolve(__dirname, '..', '..', '..', '..', '..', '..', 'Umbraco.Community.SchemeWeaver', 'App_Plugins', 'SchemeWeaver', 'src');
const BRIDGE_IMPORT = '../../../../../Umbraco.Community.SchemeWeaver/App_Plugins/SchemeWeaver/src/';

function fail(message: string): never {
  throw new Error(`[mocked-backoffice] ${message}`);
}

function resolveUmbracoClientPath(): string {
  const raw = process.env.UMBRACO_CLIENT_PATH;
  if (!raw) fail('UMBRACO_CLIENT_PATH is not set.');
  const resolved = resolve(raw);
  if (!existsSync(join(resolved, 'package.json'))) fail(`"${resolved}" is not an Umbraco.Web.UI.Client checkout.`);
  return resolved;
}

function assertPatchApplied(umbracoClientPath: string): void {
  const mocksIndex = join(umbracoClientPath, 'src', 'mocks', 'index.ts');
  if (!existsSync(mocksIndex)) fail(`Could not find ${mocksIndex} — is UMBRACO_CLIENT_PATH a v${PINNED_UMBRACO_VERSION} checkout?`);
  if (!readFileSync(mocksIndex, 'utf-8').includes('addMockHandlers')) {
    fail(
      'The Umbraco-CMS clone is missing the `addMockHandlers` hook. Apply the patch shipped with the core harness:\n' +
        `  git -C "${umbracoClientPath}" apply <repo>/src/Umbraco.Community.SchemeWeaver/App_Plugins/SchemeWeaver/tests/mocked-backoffice/patches/umbraco-cms-v17.2.2-addmockhandlers.patch`,
    );
  }
}

function rewriteBridge(dir: string): void {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      rewriteBridge(path);
      continue;
    }
    if (!entry.endsWith('.ts')) continue;
    const text = readFileSync(path, 'utf-8');
    if (!text.includes(BRIDGE_IMPORT)) continue;
    writeFileSync(path, text.split(BRIDGE_IMPORT).join('../../core/'));
  }
}

function buildCompositeMirror(umbracoClientPath: string): void {
  const mirror = join(umbracoClientPath, MIRROR_SUBPATH);
  if (!existsSync(SEO_SRC)) fail(`SEO src not found at ${SEO_SRC}`);
  if (!existsSync(CORE_SRC)) fail(`Core src not found at ${CORE_SRC}`);

  if (existsSync(mirror)) {
    if (!existsSync(join(mirror, 'seo', 'manifests.ts'))) {
      fail(`Refusing to delete ${mirror} — it does not look like a SchemeWeaver SEO mirror.`);
    }
    rmSync(mirror, { recursive: true, force: true });
  }

  mkdirSync(mirror, { recursive: true });
  cpSync(CORE_SRC, join(mirror, 'core'), { recursive: true });
  cpSync(SEO_SRC, join(mirror, 'seo'), { recursive: true });
  rewriteBridge(join(mirror, 'seo', 'core-bridge'));

  writeFileSync(
    join(mirror, 'index.ts'),
    [
      '// Generated by the SEO mocked-backoffice harness: loads the core and SEO bundles together.',
      "import { manifests as coreManifests } from './core/index.js';",
      "import { manifests as seoManifests } from './seo/index.js';",
      'export const manifests = [...coreManifests, ...seoManifests];',
      '',
    ].join('\n'),
  );
}

export default function globalSetup(): void {
  const umbracoClientPath = resolveUmbracoClientPath();
  assertPatchApplied(umbracoClientPath);
  try {
    const pkg = JSON.parse(readFileSync(join(umbracoClientPath, 'package.json'), 'utf-8'));
    if (pkg?.version && pkg.version !== PINNED_UMBRACO_VERSION) {
      // eslint-disable-next-line no-console
      console.warn(`[mocked-backoffice] Umbraco-CMS ${pkg.version} differs from the pinned ${PINNED_UMBRACO_VERSION}.`);
    }
  } catch {
    /* surfaced elsewhere */
  }
  buildCompositeMirror(umbracoClientPath);
}
